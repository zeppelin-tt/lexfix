"""Обратная транслитерация: кириллическая запись английского имени → латиница.

GigaAM — русская модель, и незнакомое английское слово она часто пишет не
латиницей с опечаткой, а по-русски, как услышала: «флаттер», «вермона
перформер», «дарт». Латинский корректор такое не видит в принципе.

Идти от английского написания к русскому произношению трудно: английская
орфография нерегулярна (Moog → «муг», не «моог»). Обратное направление
гораздо проще — русская орфография фонетична, «вермона» → vermona
однозначно. Поэтому транслитерируем кириллицу в латиницу и ищем в том же
словаре тем же fuzzy-механизмом.

Два ключа сравнения:

  full     — прямая транслитерация: «вермона» → vermona
  skeleton — скелет из согласных: «флаттер» → fltr, Flutter → fltr

Скелет вытягивает случаи, где гласные при записи на слух поплыли
(«флаттер» vs Flutter, «муг» vs Moog) — согласные в транслитерации
устойчивы, гласные нет.
"""

import hashlib
import re

# Фонетическая транслитерация. Многобуквенные сочетания идут первыми.
_MAP = [
    ("дж", "j"), ("кс", "x"), ("ье", "ye"), ("ъе", "ye"),
    ("а", "a"), ("б", "b"), ("в", "v"), ("г", "g"), ("д", "d"),
    ("е", "e"), ("ё", "e"), ("ж", "zh"), ("з", "z"), ("и", "i"),
    ("й", "y"), ("к", "k"), ("л", "l"), ("м", "m"), ("н", "n"),
    ("о", "o"), ("п", "p"), ("р", "r"), ("с", "s"), ("т", "t"),
    ("у", "u"), ("ф", "f"), ("х", "h"), ("ц", "ts"), ("ч", "ch"),
    ("ш", "sh"), ("щ", "sch"), ("ъ", ""), ("ы", "y"), ("ь", ""),
    ("э", "e"), ("ю", "yu"), ("я", "ya"),
]

_VOWELS = set("aeiouy")
_CYRILLIC_RE = re.compile(r"[а-яёА-ЯЁ]")

# Латинские написания, которые звучат одинаково: приводим обе стороны
# к общему виду перед сравнением. Порядок важен.
_FOLD = [
    ("ph", "f"), ("ck", "k"), ("ch", "c"), ("sh", "s"), ("th", "t"),
    ("qu", "kv"), ("x", "ks"), ("q", "k"), ("w", "v"), ("c", "k"),
    ("j", "g"), ("z", "s"), ("y", "i"),
]


def has_cyrillic(s: str) -> bool:
    return bool(_CYRILLIC_RE.search(s))


def to_latin(s: str) -> str:
    """«вермона перформер» → «vermona performer»."""
    s = s.lower()
    out = []
    i = 0
    while i < len(s):
        for src, dst in _MAP:
            if s.startswith(src, i):
                out.append(dst)
                i += len(src)
                break
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


def fold(s: str) -> str:
    """Свести к произношению: Flutter → flutr. Кириллицу транслитерирует сама."""
    s = s.lower()
    if has_cyrillic(s):
        s = to_latin(s)
    for src, dst in _FOLD:
        s = s.replace(src, dst)
    s = re.sub(r"(.)\1+", r"\1", s)      # двойные согласные не слышны
    return s


def skeleton(s: str) -> str:
    """Скелет из согласных: Flutter → fltr, «флаттер» → fltr."""
    return "".join(ch for ch in fold(s) if ch.isalpha() and ch not in _VOWELS)


def ru_word_hash(word: str) -> int:
    """Стабильный 64-битный ключ русской словоформы для ru_words.bin.

    Живёт здесь, а не в corrector.py или build_lexicon.py, потому что нужен
    обоим — сборщик пишет этим индекс, корректор им же его читает, и разъехаться
    они не должны. Встроенный hash() не годится категорически: он солится на
    каждый процесс, так что записанный индекс перестал бы читаться уже
    следующим запуском.
    """
    return int.from_bytes(
        hashlib.blake2b(word.strip().lower().encode("utf-8"),
                        digest_size=8).digest(), "big")
